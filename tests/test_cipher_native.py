            self.assertEqual((1, 1), tuple(s.engine._numeric_stat(token.object_id, stat) for stat in ('power', 'toughness')))
            self.assertIn('flying', s.engine._combat_keywords(token))
            grants = granted_triggered_specs(canonical_ability_fragments(s.engine._effective_card_data(token)['ability_fragments']))
            self.assertEqual(1 if token.object_id == creature.object_id else 0, len(grants))
