    def test_actual_cipher_link_survives_vehicle_noncreature_interval_and_recrew(self):
        s = self.session(702990107)
        source = self.add(s.engine, 'Last Thoughts', zone='hand')
        vehicle = self.add(s.engine, 'Renegade Freighter')
        worker = self.add(s.engine, 'Gigantosaurus')
        self.add(s.engine, 'Fervor')
        self.assert_closed(s, source)
        self.ready(s, {'C': 3, 'U': 1})
        crew = next(a for a in s.engine._activated_abilities(vehicle) if a.crew_threshold == 2)
        self.priority(s, 'A')
        result = s.act('pilot:A', {'action_id': 'activate:' + vehicle.ref + ':' + crew.ability_id, 'cost_cards': [worker.ref]})
        self.assertTrue(result.ok, result.summary)
        self.settle(s)
        self.cast(s, 'A', source)
        self.assertEqual('semantic.choice', self.resolve(s).kind)
        self.choose_as(s, 'A', cards=[vehicle.ref])
        self.settle(s)
        self.finish_turn(s)
        self.assertNotIn('creature', s.engine._effective_card_data(s.state.cards[vehicle.object_id])['type_line'].casefold())
        from quorune.rules.cipher import current_cipher_encoding
        self.assertIsNotNone(current_cipher_encoding(s.state, s.state.cards[source.object_id]))
        for _ in range(3):
            self.finish_turn(s)
        self.until(s, lambda s: s.state.phase == 'precombat_main' and s.state.pending_decision is not None and s.state.pending_decision.kind == 'priority')
        self.priority(s, 'A')
        result = s.act('pilot:A', {'action_id': 'activate:' + vehicle.ref + ':' + crew.ability_id, 'cost_cards': [worker.ref]})
        self.assertTrue(result.ok, result.summary)
        self.settle(s)
        self.attack(s, [(vehicle, 'B')])
        self.settle(s)
        self.until(s, lambda s: any(i.semantic_key.startswith('builtin:cipher:') for i in s.state.stack))
        self.assertEqual('selection.exile_cast', self.resolve(s).kind)
        self.choose_as(s, 'A', choice='decline')
        self.settle(s)
        self.assertIsNotNone(current_cipher_encoding(s.state, s.state.cards[source.object_id]))
        self.private(s)
        self.replay(s, load=True)

