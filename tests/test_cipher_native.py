    def test_actual_cipher_control_change_locks_damage_trigger_controller_after_creature_departure(self):
        s = self.session(702990102)
        source = self.add(s.engine, 'Last Thoughts', seat='B', zone='hand')
        creature = self.add(s.engine, 'Grizzly Bears', seat='B')
        theft = self.add(s.engine, 'Act of Treason', zone='hand')
        bounce = self.add(s.engine, 'Unsummon', seat='B', zone='hand')
        self.add(s.engine, 'Island', seat='B')
        self.add(s.engine, 'Vedalken Orrery', seat='B')
        self.assert_closed(s, source)
        self.ready(s, {'C': 2, 'R': 1})
        s.state.players['B'].mana_pool.update(C=3, U=1)
        self.checkpoint(s)
        self.cast(s, 'B', source)
        self.assertEqual('semantic.choice', self.resolve(s).kind)
        self.choose_as(s, 'B', cards=[creature.ref])
        self.settle(s)
        self.cast(s, 'A', theft, [creature.ref])
        self.settle(s)
        self.assertEqual('A', s.state.cards[creature.object_id].controller)
        self.attack(s, [(creature, 'C')])
