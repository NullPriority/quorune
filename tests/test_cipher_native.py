        self.resolve_top(s)
        self.assertEqual('hand', s.state.cards[creature.object_id].zone)
        self.assertEqual('selection.exile_cast', self.resolve(s).kind)
        before = {seat: len(s.state.players[seat].zones['hand']) for seat in 'AB'}
