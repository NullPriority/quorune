    def test_actual_last_thoughts_encodes_after_draw_and_combat_copy_does_not_encode(self):
        s = self.session(702990100)
        source = self.add(s.engine, 'Last Thoughts', zone='hand')
        creature = self.add(s.engine, 'Grizzly Bears')
        creature.acquired_control_turn_count = -1
        foreign = self.add(s.engine, 'Grizzly Bears', seat='B', ref='foreign-cipher-creature')
        self.assert_closed(s, source)
        self.ready(s, {'C': 3, 'U': 1})
        self.cast(s, 'A', source)
        hand = len(s.state.players['A'].zones['hand'])
        self.assertEqual('semantic.choice', self.resolve(s).kind)
        self.assertEqual(hand + 1, len(s.state.players['A'].zones['hand']))
        self.assertEqual('stack', s.state.cards[source.object_id].zone)
        before = authoritative_state_hash(s.state)
        self.assertFalse(s.act('pilot:A', {'action_id': 'choose', 'cards': [foreign.ref]}).ok)
        self.assertEqual(before, authoritative_state_hash(s.state))
        s = self.replay(s, load=True)
        self.choose_as(s, 'A', cards=[creature.ref])
        self.settle(s)
        self.assertEqual('exile', s.state.cards[source.object_id].zone)
        self.attack(s, [(creature, 'B')])
        self.until(s, lambda s: any(item.semantic_key.startswith('builtin:cipher:') for item in s.state.stack))
        self.assertEqual(38, s.state.players['B'].life)
        self.assertEqual('selection.exile_cast', self.resolve(s).kind)
        s = self.replay(s, load=True)
        before = len(s.state.players['A'].zones['hand'])
        self.choose_as(s, 'A', choice='cast')
        self.settle(s)
        self.assertEqual(before + 1, len(s.state.players['A'].zones['hand']))
        self.assertEqual('exile', s.state.cards[source.object_id].zone)
        self.assertFalse(any(c.is_card_copy and c.zone == 'exile' for c in s.state.cards.values()))
        self.private(s)
        self.replay(s, load=True)

